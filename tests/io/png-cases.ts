/** Runner-agnostic assertion surface: bun:test and node:test entries adapt to this. */
export interface CaseCheck {
	equal(actual: unknown, expected: unknown, message?: string): void;
	deepEqual(actual: unknown, expected: unknown, message?: string): void;
	ok(value: unknown, message?: string): void;
	fail(message: string): never;
	throwsCode(fn: () => unknown, code: string, message?: string): void;
}

export interface PngCase {
	name: string;
	/** Overrides the framework's default timeout for cases that are slow by design. */
	timeoutMs?: number;
	run(check: CaseCheck): void;
}

function fromBase64(literal: string): Uint8Array {
	return new Uint8Array(Buffer.from(literal, "base64"));
}

function bytesEqual(
	check: CaseCheck,
	actual: Uint8Array,
	expected: readonly number[],
	message: string,
): void {
	check.equal(actual.length, expected.length, `${message} (length)`);
	for (let i = 0; i < expected.length; i += 1) {
		check.equal(actual[i], expected[i], `${message} (byte ${i})`);
	}
}

