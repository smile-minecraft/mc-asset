/** Families in frozen export order: builtin twelve first, then extras. */
export function paletteFamilyOrder(familyIds: readonly string[]): string[] {
	const extras = familyIds
		.filter((id) => !(BUILTIN_FAMILY_ORDER as readonly string[]).includes(id))
		.sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
	return [...BUILTIN_FAMILY_ORDER, ...extras];
}
